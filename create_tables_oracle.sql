-- ── 1. EMPRESAS ──────────────────────────────────────────────
CREATE TABLE ml_empresa (
    id        NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR2(200)  NOT NULL,
    cuit      VARCHAR2(13)   NOT NULL UNIQUE,
    direccion VARCHAR2(300),
    telefono  VARCHAR2(50),
    activa    NUMBER(1,0)    DEFAULT 1 NOT NULL
);

-- ── 2. PACIENTES ─────────────────────────────────────────────
CREATE TABLE ml_paciente (
    id              NUMBER(19,0)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido        VARCHAR2(200) NOT NULL,
    nombres         VARCHAR2(200) NOT NULL,
    dni             VARCHAR2(30)  NOT NULL UNIQUE,
    direccion       VARCHAR2(300) DEFAULT '' NOT NULL,
    tel_movil       VARCHAR2(50)  DEFAULT '' NOT NULL,
    email           VARCHAR2(200) DEFAULT '' NOT NULL,
    cuil            VARCHAR2(11)  DEFAULT '' NOT NULL,
    estado_civil    VARCHAR2(1)   DEFAULT '' NOT NULL,
    nacionalidad    VARCHAR2(100) DEFAULT '' NOT NULL,
    sexo            VARCHAR2(1)   DEFAULT '' NOT NULL,
    tarea_propuesta CLOB          DEFAULT '' NOT NULL,
    empresa_id      NUMBER(19,0)  REFERENCES ml_empresa(id) ON DELETE SET NULL
);

-- ── 3. ESPECIALIDADES ────────────────────────────────────────
CREATE TABLE ml_especialidad (
    id     NUMBER(19,0)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL
);

-- ── 4. PROFESIONALES ─────────────────────────────────────────
CREATE TABLE ml_profesional (
    id              NUMBER(19,0)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(100) NOT NULL,
    apellido        VARCHAR2(100) NOT NULL,
    matricula       VARCHAR2(50)  NOT NULL,
    especialidad_id NUMBER(19,0)  REFERENCES ml_especialidad(id) ON DELETE SET NULL
);

-- ── 5. INFORMES MÉDICOS ───────────────────────────────────────
CREATE TABLE ml_informe (
    id                  NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto_informe       CLOB           NOT NULL,
    archivo_pdf         VARCHAR2(255),
    estado              VARCHAR2(20)   DEFAULT 'BORRADOR' NOT NULL,
    fecha_creacion      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    profesional_id      NUMBER(19,0)   NOT NULL REFERENCES ml_profesional(id),
    paciente_id         NUMBER(19,0)   REFERENCES ml_paciente(id)  ON DELETE SET NULL,
    firma_timestamp     TIMESTAMP,
    -- turno_id se agrega después (ML_RESERVA_TURNO aún no existe)
    turno_id            NUMBER(19,0)   -- FK se define con ALTER más abajo
);

-- ── 6. FIRMA DIGITAL ─────────────────────────────────────────
CREATE TABLE ml_firmadigi (
    id              NUMBER(19,0)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imagen_firma    VARCHAR2(255),
    hash_firma      VARCHAR2(255) DEFAULT '' NOT NULL,
    profesional_id  NUMBER(19,0)  NOT NULL UNIQUE REFERENCES ml_profesional(id) ON DELETE CASCADE
);

-- ── 7. PERFIL PROFESIONAL (link user ↔ profesional) ──────────
-- Requiere que la tabla auth_user de Django ya exista.
-- Si todavía no hiciste `migrate` para auth, correla primero:
--   python manage.py migrate auth
--   python manage.py migrate contenttypes
CREATE TABLE ml_perfil_profesional (
    id              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER(19,0) NOT NULL UNIQUE REFERENCES auth_user(id) ON DELETE CASCADE,
    profesional_id  NUMBER(19,0) NOT NULL UNIQUE REFERENCES ml_profesional(id) ON DELETE CASCADE
);

-- ── 8. RESERVA DE TURNOS ─────────────────────────────────────
CREATE TABLE ml_reserva_turno (
    id                  NUMBER(19,0)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id         NUMBER(19,0)  NOT NULL REFERENCES ml_paciente(id),
    profesional_id      NUMBER(19,0)  NOT NULL REFERENCES ml_profesional(id),
    fecha_visita        DATE          NOT NULL,
    hora_visita         DATE          NOT NULL,   -- Oracle usa DATE para TIME también
    estado              VARCHAR2(12)  DEFAULT 'PENDIENTE' NOT NULL,
    observaciones       CLOB          DEFAULT '' NOT NULL,
    fecha_creacion      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- FK de ml_informe → ml_reserva_turno (ahora que la tabla existe)
ALTER TABLE ml_informe
    ADD CONSTRAINT fk_informe_turno
    FOREIGN KEY (turno_id) REFERENCES ml_reserva_turno(id) ON DELETE SET NULL;

